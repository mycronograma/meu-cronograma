test('public auth pages are stable on mobile and desktop', async ({ page }) => {
  const consoleProblems = [];
  page.on('console', (msg) => {
    const text = msg.text();
    if ((msg.type() === 'error' || msg.type() === 'warning') && !/favicon|DEP0205|scroll-behavior|sticky/i.test(text)) {
      consoleProblems.push(`${msg.type()}: ${text}`);
    }
  });

  for (const viewport of [
    { width: 390, height: 844 },
    { width: 1366, height: 768 },
  ]) {
    await page.setViewportSize(viewport);
    for (const path of ['/login', '/register', '/forgot-password', '/reset-password']) {
      await auditPage(page, path);
    }
  }

  await page.goto('/login', { waitUntil: 'networkidle' });
  await page.locator('input[name="email"]').fill('email-invalido');
  await page.locator('input[name="password"]').fill('');
  await page.locator('form button[type="submit"]').click();
  await expect(page.getByText(/Informe um e-mail valido/i)).toBeVisible();

  await page.goto('/forgot-password', { waitUntil: 'networkidle' });
  await page.locator('input[type="email"]').fill('qa@nexora.local');
  await page.locator('form button[type="submit"]').click();
  await expect(page.getByText(/recuperacao real depende/i)).toBeVisible();

  expect(consoleProblems).toEqual([]);
});

