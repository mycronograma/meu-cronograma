async function auditPage(page, path) {
  await page.goto(path, { waitUntil: 'networkidle' });
  await page.waitForTimeout(350);
  const bodyText = await page.locator('body').innerText();
  const layout = await page.evaluate(() => ({
    overflowX: document.documentElement.scrollWidth > window.innerWidth + 8,
    blank: document.body.innerText.trim().length < 20,
  }));

  expect(bodyText).not.toMatch(/undefined|NaN|Invalid Date|\[object Object\]/i);
  expect(bodyText).not.toMatch(/Application error|Unhandled Runtime Error|TypeError|ReferenceError/i);
  expect(layout.overflowX).toBe(false);
  expect(layout.blank).toBe(false);
}

